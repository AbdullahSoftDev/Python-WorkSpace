# Arithmetic
a, b = 10, 3
print(f"Addition: {a + b}")
print(f"Subtraction: {a - b}")
print(f"Multiplication: {a * b}")
print(f"Division: {a / b}")
print(f"Floor Division: {a // b}")
print(f"Modulus: {a % b}")
print(f"Exponent: {a ** b}")

# Comparison
print(f"Equal: {a == b}")
print(f"Not Equal: {a != b}")
print(f"Greater: {a > b}")
print(f"Less: {a < b}")

# Logical
x, y = True, False
print(f"And: {x and y}")
print(f"Or: {x or y}")
print(f"Not: {not x}")

# Assignment
c = 5
c += 3
print(f"Assignment: {c}")

# Identity
list1 = [1, 2]
list2 = [1, 2]
list3 = list1
print(f"Is: {list1 is list3}")
print(f"Is Not: {list1 is not list2}")

# Membership
numbers = [1, 2, 3, 4]
print(f"In: {2 in numbers}")
print(f"Not In: {5 not in numbers}")
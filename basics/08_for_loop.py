# Iterate list
fruits = ["apple", "banana", "cherry"]
for fruit in fruits:
    print(fruit)

# Range
for i in range(5):
    print(i)

# Enumerate
for index, fruit in enumerate(fruits):
    print(f"{index}: {fruit}")

# Dictionary
person = {"name": "Alice", "age": 25}
for key, value in person.items():
    print(f"{key}: {value}")